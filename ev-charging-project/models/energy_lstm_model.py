"""
LSTM Energy Consumption Prediction Model
=========================================
Phase 16: Trains and evaluates a recurrent LSTM neural network to predict
future EV battery energy consumption (target: target_future_energy_kwh)
from sequential driving telemetry observations.

IMPORTANT SYNTHETIC-DATA DISCLOSURE:
-------------------------------------
- This model is trained and evaluated strictly on synthetic/simulated Virtual EV data
  generated by the project's data collection pipeline (Phases 12 & 15).
- Target energy represents the next 30-second interval (horizon H=6 timesteps)
  predicted from the preceding 100-second driving observation (window L=20 timesteps).
- The evaluation metrics report the model's goodness-of-fit on this simulated
  distribution and MUST NOT be presented or interpreted as validated real-world
  physical EV measurements.

Input Shape:
- (timesteps=20, features=12)

Architecture:
- Input(shape=(20, 12))
- LSTM(64, activation='tanh', recurrent_activation='sigmoid')
- Dropout(0.2)
- Dense(32, activation='relu')
- Dense(1, activation='linear')

Artifacts Saved:
- models/artifacts/energy_lstm_model.keras (Trained Keras Model)
- models/artifacts/energy_lstm_model_metadata.json (Evaluation metrics & schema)
- models/artifacts/energy_lstm_loss_history.png (Training loss curve)
- models/artifacts/energy_lstm_predictions.png (Diagnostic actual vs predicted plot)

Usage:
    python models/energy_lstm_model.py
    python models/energy_lstm_model.py --epochs 25 --batch-size 256 --seed 42
"""

